"""Losslessly pack official RNF source pages for the Git handoff."""
from pathlib import Path
import zipfile,json,hashlib
ROOT=Path(__file__).resolve().parents[1];E=ROOT/'evidence/corridor_batch_v0.5'
def pack():
 paths=sorted(E.glob('rnf_*.geojson'))+sorted(E.glob('rnf*_ids_*.json'))
 target=E/'official_RNF_source_pages.zip'
 if target.exists():
  if paths:raise ValueError('Archive already exists; retain this frozen version and package refreshed sources separately')
  with zipfile.ZipFile(target) as z:
   if z.testzip() is not None:raise ValueError('Existing source archive is corrupt')
  print('Existing RNF archive retained');return
 if not paths:raise ValueError('No loose source pages available to pack')
 with zipfile.ZipFile(target,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=6) as z:
  for p in paths:z.write(p,p.name)
 with zipfile.ZipFile(target) as z:
  for p in paths:
   if z.read(p.name)!=p.read_bytes():raise ValueError('Source archive failed round-trip')
 records=[]
 for name in ['roads_acquisition_manifest.json','roads_east_acquisition_manifest.json']:
  for r in json.loads((E/name).read_text()):r.update(archive_file=str(target.relative_to(ROOT)),archive_member=Path(r['file']).name);records.append(r)
 (E/'packed_road_acquisition_manifest.json').write_text(json.dumps(dict(archive_file=str(target.relative_to(ROOT)),archive_sha256=hashlib.sha256(target.read_bytes()).hexdigest(),resources=records,notes='Raw source pages/ID responses retained losslessly. Loose file paths in original manifests are logical acquisition locations; use archive_member. Full combined GeoJSON is regenerated by source-page union and source NGD_UID deduplication.'),indent=2)+'\n')
 # All bytes verified before removing redundant local copies.
 for p in paths:p.unlink()
 for p in [E/'official_roads.geojson',E/'official_roads_east.geojson']:p.unlink(missing_ok=True)
 print('RNF archive bytes',target.stat().st_size,'source members',len(paths))
if __name__=='__main__':pack()
